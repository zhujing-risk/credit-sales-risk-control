# -*- coding: utf-8 -*-
"""
Prompt 层 — 结构化 Prompt 设计
================================================================
每个场景的 Prompt 遵循同一结构：角色设定 → 任务 → 风控约束 → 输出格式。

设计原则（面试可讲）：
  1. 角色设定让模型进入「风控专家」心智，提升输出专业度；
  2. 约束明确「结论必须来自工具数据」，防止模型编造风险；
  3. 输出格式限定结构，保证下游可解析、可评测。
"""

# 系统 Prompt：贯穿所有场景的角色与底线约束
SYSTEM_PROMPT = """你是一名资深的风控分析助手，服务于服装批发行业的赊销风控场景。
你的职责是帮助批发商老板判断「下游客户能否赊销、有无跑路风险、如何催收」。

必须遵守的约束：
1. 所有结论必须基于工具返回的真实数据，不得编造任何数字或事实；
2. 输出面向不懂风控的老板，用通俗语言，但保留可解释性（说清楚为什么）；
3. 催收话术必须合规、得体：禁止辱骂、威胁、骚扰、恐吓性内容；
4. 金额统一用「X万」表述，保留 1 位小数。
"""


def build_profile_task(name: str) -> str:
    """画像场景：生成客户信用摘要。"""
    return f"""请调用工具获取客户「{name}」的信用画像数据，然后用一句话向老板说明：
这个客户能不能赊、建议赊多少、依据是什么。
输出格式：一句话，包含「信用分、风险标签、建议赊销上限、核心依据」。"""


def build_warning_task(name: str) -> str:
    """预警场景：把规则命中的信号转成老板看得懂的预警。"""
    return f"""请调用工具获取客户「{name}」的跑路风险检测结果，然后生成一条预警推送。
输出格式：
  第一行：⚠️ 必须包含客户名「{name}」和风险等级（如「⚠️ {name} · 高危」）
  第二行：触发的原因（逐条列出，用通俗语言解释每条信号意味着什么）
  第三行：建议动作（一句话，如「建议暂停赊销并优先催收」）。"""


def build_collection_task(name: str, overdue_days: int) -> str:
    """催收场景：生成合规、得体、有力度的话术。"""
    return f"""请调用工具获取客户「{name}」的催收策略，然后生成一条针对「逾期 {overdue_days} 天」的催收话术。
要求：
  1. 语气得体但有力度，既要催回款，又不破坏长期合作关系；
  2. 不得出现任何辱骂、威胁、骚扰性措辞；
  3. 直接输出话术原文，不要解释。"""
